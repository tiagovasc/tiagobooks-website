import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {writeFile,mkdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import {webcrypto} from 'node:crypto';
const dir=path.resolve('node_modules/.cache/integration-protected-test');await mkdir(dir,{recursive:true});
const target=path.join(dir,'protected-fixture.mjs');
await build({entryPoints:['src/lib/protect.ts'],outfile:target,bundle:true,platform:'node',format:'esm',packages:'external'});
const {encryptHtml,markdownToHtml}=await import(pathToFileURL(target));
const sentinel='UNIQUE-PRIVATE-CONTENT-c50a33';const html=await markdownToHtml('## Heading\n\n'+sentinel+' **bold** and $12.\n\nhttps://youtu.be/D6hjtY0cm3s');
assert.match(html,/<strong>bold<\/strong>/);assert.match(html,/youtube-nocookie/);
const password='isolated-protection-fixture';const payload=await encryptHtml(html,password);assert.ok(!JSON.stringify(payload).includes(sentinel));
const bytes=x=>Buffer.from(x,'base64');
const base=await webcrypto.subtle.importKey('raw',new TextEncoder().encode(password),'PBKDF2',false,['deriveKey']);
const key=await webcrypto.subtle.deriveKey({name:'PBKDF2',salt:bytes(payload.salt),iterations:payload.iterations,hash:'SHA-256'},base,{name:'AES-GCM',length:256},false,['decrypt']);
const decrypted=await webcrypto.subtle.decrypt({name:'AES-GCM',iv:bytes(payload.iv)},key,bytes(payload.data));
assert.equal(new TextDecoder().decode(decrypted),html);
console.log('Protected Markdown renderer and AES-GCM round trip passed.');
