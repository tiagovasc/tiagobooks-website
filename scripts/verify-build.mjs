// Post-build sanity checks: URL shape, drafts hidden, feed/sitemap contents, protected entries encrypted and decryptable.
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { webcrypto } from 'node:crypto';
const pw = process.env.SITE_PASSWORD ?? 'changeme';
let fail = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const f = (p) => readFileSync('dist/' + p, 'utf8');
ok(existsSync('dist/index.html'), 'home');
ok(existsSync('dist/posts.html'), '/posts list');
ok(existsSync('dist/search.html'), '/search');
ok(existsSync('dist/pagefind/pagefind.js'), 'pagefind index');
ok(existsSync('dist/posts_feed'), '/posts_feed (atom)');
ok(existsSync('dist/robots.txt') && f('robots.txt').includes('GPTBot'), 'robots.txt blocks AI bots');
ok(existsSync('dist/sitemap-index.xml'), 'sitemap-index.xml');
ok(!existsSync('dist/posts/sample-draft.html'), 'draft not built');
ok(!f('index.html').includes('Sample Draft'), 'draft not listed');
ok(!f('index.html').includes('Sample Private Post'), 'protected not listed');
ok(!f('posts_feed').includes('Sample Private Post'), 'protected not in feed');
ok(!f('sitemap-0.xml').includes('sample-private-post'), 'protected not in sitemap');
ok(f('posts_feed').includes('<content type="html">'), 'feed has full content');
ok(existsSync('dist/tag/Book-Reviews.html'), '/tag/Book-Reviews');
const priv = f('posts/sample-private-post.html');
ok(!priv.includes('Secret'), 'protected body not in HTML');
ok(priv.includes('noindex'), 'protected is noindex');
const payload = JSON.parse(priv.match(/data-payload="([^"]+)"/)[1].replace(/&#34;|&quot;/g, '"'));
const from64 = (s) => Uint8Array.from(Buffer.from(s, 'base64'));
const base = await webcrypto.subtle.importKey('raw', new TextEncoder().encode(pw), 'PBKDF2', false, ['deriveKey']);
const key = await webcrypto.subtle.deriveKey({ name: 'PBKDF2', salt: from64(payload.salt), iterations: payload.iterations, hash: 'SHA-256' }, base, { name: 'AES-GCM', length: 256 }, false, ['decrypt']);
const plain = new TextDecoder().decode(await webcrypto.subtle.decrypt({ name: 'AES-GCM', iv: from64(payload.iv) }, key, from64(payload.data)));
ok(plain.includes('Secret') && plain.includes('katex'), 'protected payload decrypts (with math rendered)');
process.exit(fail ? 1 : 0);
